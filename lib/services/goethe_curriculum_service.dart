  /// Returns the certified Goethe curriculum level ('A1', 'A2', 'B1') if verified, or null.
  /// Resolves either the direct word or its base lemma (e.g. 'gestiegen' -> 'steigen' -> B1).
  static String? getGoetheLevel(String word, {String? baseForm}) {
    final clean = word.toLowerCase().trim();
    if (_goetheA1Words.contains(clean)) return 'A1';
    if (_goetheA2Words.contains(clean)) return 'A2';
    if (_goetheB1Words.contains(clean)) return 'B1';

    if (baseForm != null && baseForm.trim().isNotEmpty) {
      final cleanBase = baseForm.toLowerCase().trim();
      if (_goetheA1Words.contains(cleanBase)) return 'A1';
      if (_goetheA2Words.contains(cleanBase)) return 'A2';
      if (_goetheB1Words.contains(cleanBase)) return 'B1';
    }

    return null;
  }

  /// Returns true if the word or its base lemma is certified in official Goethe-Institut core vocabulary.
  static bool isGoetheCertified(String word, {String? baseForm}) {
    return getGoetheLevel(word, baseForm: baseForm) != null;
  }
